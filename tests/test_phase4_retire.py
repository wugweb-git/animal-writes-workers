"""Sourcing restructure phase 4 (owner, 25 Oct 2026): the site retires the old lists. Its policy then sends, beside
`defaults`, the press switches and the tag rules (`topic_tags`), only the blocks: sources_v2, the keyword table
(top-level `keywords` and `config.keywords_v2`), category_names, sections_v2, schema and match; `relevance` holds only
the switch. The workers accept that shape on its own (Sources sync, run, backfill, research) and prefer it whenever it is
there; the v1 code paths stay (owner, 25 Oct 2026: "don't delete the old version"), so a site rolled back to v1 and a
sources.yaml from before phase 2 are still read as before.

`phase4()` builds the phase 4 policy from the phase 2 fixture (tests/fixtures/sourcing_phase2_policy.json, generated by
the site's code from the live lists of 25 Oct 2026) by removing what the site's phase 4 removes."""

import copy
import importlib.util
import json
from pathlib import Path

import yaml

from aw_workers import keywords, matcher, policy, run, sources

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "sourcing_phase2_policy.json").read_text(encoding="utf-8"))

# What the site's phase 4 takes out of the policy (plugins/aw-sourcing/includes/retire-model.php AW_RETIRE_V1_CONFIG).
V1_CONFIG_KEYS = ("keywords", "sources", "categories", "sections")


def today():
    return copy.deepcopy(FIXTURE["today"])


def phase4():
    raw = copy.deepcopy(FIXTURE["migrated"])
    raw["relevance"] = {"enabled": raw["relevance"]["enabled"]}
    for k in V1_CONFIG_KEYS:
        raw["config"].pop(k, None)
    raw["config"]["press"].pop("queries", None)
    raw["config"]["sections_v2"] = SECTIONS_V2
    return raw


SECTIONS_V2 = [{"post_type": "aw_news", "label": "News", "worker_type": "news", "categories": [], "tags": [], "tag_rules": [],
                "summary": "aw_news"},
               {"post_type": "aw_legal", "label": "Library", "worker_type": "legal", "categories": [], "tags": [],
                "tag_rules": [], "summary": "aw_legal"}]


def built(raw: dict):
    """What run.main builds from a policy: the site's lists (or None), its sources and searches."""
    lists = sources.site_lists(raw)
    assert lists is not None
    return lists, run.keyword_searches(sources.load_sources_data(lists)[0], lists)


def test_phase4_policy_has_no_old_keys():
    raw = phase4()
    assert set(raw["relevance"]) == {"enabled"}
    assert not set(V1_CONFIG_KEYS) & set(raw["config"]) and "queries" not in raw["config"]["press"]
    assert {"sources_v2", "keywords_v2", "category_names", "match", "schema", "topic_tags", "defaults"} <= set(raw["config"])


def test_acceptance_identical_searches_from_the_v2_data_alone():
    """Plan §6, still in phase 4: the (feed id, query URL) list from the phase 4 policy (no old keys at all) equals the
    one today's v1 lists give (read the old way, as an old sources.yaml would be)."""
    v1_lists = sources.with_v2_blocks(today()["config"], today())
    assert not sources.is_v2(v1_lists)  # phase 1: no keyword table
    v1 = run.keyword_searches(sources.load_sources_data(v1_lists)[0], v1_lists)
    _, v2 = built(phase4())
    gn = lambda xs: sorted((s.id, s.url) for s in xs if "news.google.com" in s.url)  # noqa: E731
    assert gn(v1) == gn(v2) and len(gn(v2)) == 30
    assert sorted((s.id, s.url) for s in v1) == sorted((s.id, s.url) for s in v2)


def test_with_the_v2_blocks_the_old_keys_beside_them_change_nothing():
    """Until the site's migration runs it still sends the old keys; with the v2 blocks there, whatever they hold changes
    nothing (v2 is preferred)."""
    clean_lists, clean = built(phase4())
    cats = copy.deepcopy(sources.CATEGORIES)
    raw = copy.deepcopy(FIXTURE["migrated"])
    raw["config"]["sections_v2"] = SECTIONS_V2
    raw["relevance"].update(strong=["zzz only old"], exclude=["animal"], animal=[], context=[])
    raw["config"]["keywords"] = ["zzz only old"]
    raw["config"]["categories"] = {"wildlife": ["zzz only old"]}
    raw["config"]["sections"] = {"aw_news": {"categories": ["zzz"], "tags": []}}
    raw["config"]["press"]["queries"] = ["zzz only old"]
    raw["config"]["sources"] = [{"id": "old-only", "name": "Old", "kind": "rss", "type": "news", "url": "https://old.example/feed"}]
    lists, got = built(raw)
    assert [(s.id, s.url, s.keywords, s.categories) for s in got] == [(s.id, s.url, s.keywords, s.categories) for s in clean]
    assert sources.CATEGORIES == cats and "zzz" not in json.dumps(sources.SECTIONS)
    assert keywords.press_config(lists)["queries"] == keywords.press_config(clean_lists)["queries"] == today()["config"]["press"]["queries"]
    p, q = policy.Policy.from_json(raw), policy.Policy.from_json(phase4())
    assert (p.strong, p.animal, p.context, p.exclude) == (q.strong, q.animal, q.context, q.exclude)
    assert "zzz only old" not in p.strong and "animal" not in p.exclude


def test_site_lists_in_either_shape():
    assert sources.site_lists(phase4()) is not None  # no config.sources at all: still the site's lists
    assert sources.site_lists(today()) is not None  # v1 (a site rolled back): still read, as before
    assert sources.site_lists({"publishers": {}}) is None  # "Workers use these lists" off: no config
    broken = phase4()
    broken["config"]["sources_v2"][0].pop("url")
    assert sources.site_lists(broken) is None  # neither a whole v2 block nor a v1 sources list: sources.yaml


def test_policy_lists_from_the_table_and_v1_kept_as_fallback():
    p = policy.Policy.from_json(phase4())
    assert p.strong and p.exclude and "zzz" not in p.strong
    v1 = policy.Policy.from_json({"publishers": {"blocked": ["x.com"]}, "relevance": {"enabled": True, "strong": ["dog"]}})
    assert v1.strong == ["dog"] and v1.relevance_on  # a site rolled back to v1: its lists, as before


def test_an_old_sources_yaml_is_still_read():
    """The fallback keeps working whatever its age: today's committed sources.yaml and a phase 1 copy."""
    old = yaml.safe_load((ROOT / "sources.yaml").read_text(encoding="utf-8"))
    for data in (copy.deepcopy(old), copy.deepcopy(today()["config"])):
        if sources.is_v2(data):
            continue  # a sources.yaml Sources sync already wrote in the new shape
        got, defaults = sources.load_sources_data(data)
        assert got and defaults and sources.CATEGORIES and not sources.keyword_table_on()
        assert run.keyword_searches(got, data)


def test_sources_yaml_written_from_the_phase4_policy_reads_the_same(tmp_path, monkeypatch):
    spec = importlib.util.spec_from_file_location("sync_sources", ROOT / "scripts" / "sync_sources.py")
    sync = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(sync)
    raw = phase4()
    path = tmp_path / "sources.yaml"
    monkeypatch.setenv("AW_SOURCES", str(path))
    assert sync.sync_lists(raw) is True
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    assert "sources" not in data and data["keywords_v2"] == raw["config"]["keywords_v2"]
    _, from_site = built(raw)
    from_yaml = run.keyword_searches(sources.load_sources_data(data)[0], data)
    assert [(s.id, s.url) for s in from_yaml] == [(s.id, s.url) for s in from_site]
    assert sync.sync_lists(raw) is False  # unchanged
    assert sync.sync_lists({"publishers": {}}) is None  # the lists' switch off: sources.yaml stays as it is
    assert yaml.safe_load(path.read_text(encoding="utf-8")) == data


def test_word_matching_with_the_table():
    built(phase4())
    assert matcher.word_mode() and sources.keyword_table_on()
