# ---- categories at ingest (plan §6) ----


class _Backend:
    name = "fake"

    def __init__(self, reply):
        self.reply = reply

    def ask(self, prompt):
        return self.reply


def _item(title, cats=(), text=""):
    src = sources.Source(id="gnews-kw-x", name="X", kind="rss", type="news", url="u", categories=list(cats))
    return sources.Item(src, title, "https://e.example/1", None, text)


def test_categories_from_the_keyword_the_text_and_the_ai():
    sources.load_sources_data(lists_of(migrated()))
    allowed = sources.allowed_categories("news")
    item = _item("Court hears plea on dog feeding", cats=["community-dogs"])
    got = summarise.pick_categories(None, item, "", allowed)
    assert got[0] == "community-dogs"
    # the keyword's categories come first, then whole-word text matches, then the relevance check's choice
    item = _item("Rabies vaccination camp held", cats=["community-dogs"])
    got = summarise.pick_categories(None, item, "", allowed, ai_choice="veterinary-care")
    assert got[0] == "community-dogs" and "rabies-public-health" in got and got[-1] == "veterinary-care"
    # the AI's choice is not repeated when the keywords already gave it
    assert summarise.pick_categories(None, item, "", allowed, ai_choice="community-dogs").count("community-dogs") == 1


def test_the_section_rule_limits_and_the_ai_picks_when_nothing_is_left():
    sources.load_sources_data(lists_of(migrated()))
    item = _item("Plain headline with nothing", cats=["wildlife"])
    s = summarise.Summariser([_Backend("adoption")])
    assert summarise.pick_categories(s, item, "", ["adoption", "birds"], ai_choice="veterinary-care") == ["adoption"]
    assert summarise.pick_categories(None, item, "", ["wildlife"]) == ["wildlife"]


