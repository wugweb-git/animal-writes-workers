def test_sources_yaml_with_the_synced_blocks_reads_the_same(tmp_path):
    """Sources sync copies `config` (with keywords_v2, match and sources_v2) into sources.yaml: the fallback then builds
    the same searches as the site's policy."""
    raw = migrated()
    path = tmp_path / "sources.yaml"
    path.write_text(yaml.safe_dump(lists_of(raw), sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
