"""Sourcing restructure phase 2 (owner, 25 Oct 2026): the site sends its keyword table (`keywords`, and the same list as
`config.keywords_v2`) beside the v1 lists. Workers build the searches, relevance lists, keyword checks, category words
and press queries from it when it is there, and from the v1 lists otherwise.

tests/fixtures/sourcing_phase2_policy.json was generated by the site's own code from the live lists of 25 Oct 2026:
`today` is what the site sends in phase 1, `migrated` what it sends after the phase 2 migration."""

import copy
import json
from datetime import date
from pathlib import Path

import pytest
import yaml

from aw_workers import keywords, matcher, policy, press, run, sources, summarise

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "sourcing_phase2_policy.json").read_text(encoding="utf-8"))


def today():
    return copy.deepcopy(FIXTURE["today"])


def migrated():
    return copy.deepcopy(FIXTURE["migrated"])


def lists_of(raw: dict) -> dict:
    """What run.main reads from the policy: `config` plus the blocks sent beside it."""
    return sources.with_v2_blocks(raw["config"], raw)


def searches(raw: dict) -> list:
    lists = lists_of(raw)
    return run.keyword_searches(sources.load_sources_data(lists)[0], lists)


def gnews(src_list) -> list[tuple[str, str]]:
    return [(s.id, s.url) for s in src_list if "news.google.com" in s.url]


# ---- acceptance: the same Google News searches ----


def test_acceptance_v2_keywords_give_todays_v1_search_list():
    """Plan §6: the (feed id, query URL) list built from the migrated keywords equals today's v1 list."""
    v1, v2 = searches(today()), searches(migrated())
    assert sorted(gnews(v1)) == sorted(gnews(v2))
    assert len(gnews(v2)) == len(set(gnews(v2))) == 30  # the site's model: 30 = 30
    assert sorted((s.id, s.url) for s in v1) == sorted((s.id, s.url) for s in v2)  # every source, not only searches
    ids = {s.id for s in v2}
    assert {"gnews-animal-welfare", "gnews-animal-cruelty", "gnews-lab-animal-rules", "gnews-kw-stray-dogs"} <= ids
    assert "gnews-kw-animal-welfare" not in ids  # the same query as gnews-animal-welfare: fetched once, as in v1


def test_v2_searches_keep_the_feed_settings_and_the_keyword_categories():
    v1 = {s.id: s for s in searches(today())}
    v2 = {s.id: s for s in searches(migrated())}
    for sid in v1:
        assert (v2[sid].type, v2[sid].kind, v2[sid].max_items, v2[sid].file_as) == \
               (v1[sid].type, v1[sid].kind, v1[sid].max_items, v1[sid].file_as), sid
    assert v2["gnews-lab-animal-rules"].file_as == "press"
    assert v2["gnews-kw-stray-dog"].categories == ["community-dogs"]
    assert v2["gnews-kw-stray-dogs"].categories == ["community-dogs"]
    assert v2["gnews-kw-awbi"].categories == [] and v2["the-hindu-environment"].categories == []
    # the lab search's keyword check: the words mapped to Animal experimentation (owner's decision 5)
    lab = v2["gnews-lab-animal-rules"].keywords
    assert "vivisection" in lab and "CCSEA".lower() in [w.lower() for w in lab]


def test_extra_searches_only_without_the_keyword_table():
    raw = migrated()
    for k in raw["keywords"]:
        if k["label"] == "stray dogs":
            k["roles"].remove("search")
            k["searches"] = []
    raw["config"]["keywords_v2"] = raw["keywords"]
    assert "gnews-kw-stray-dogs" not in {s.id for s in searches(raw)}  # the fixed list is not added in v2
    assert "gnews-kw-stray-dogs" in {s.id for s in searches(today())}


def test_whole_feed_search_switched_off_or_incomplete_is_skipped():
    raw = migrated()
    for k in raw["keywords"]:
        if k["label"] == "lab animal rules":
            k["searches"][0]["on"] = False
        if k["label"] == "animal cruelty":
            del k["searches"][0]["kind"]
    raw["config"]["keywords_v2"] = raw["keywords"]
    ids = {s.id for s in searches(raw)}
    assert "gnews-lab-animal-rules" not in ids
    assert "gnews-animal-cruelty" not in ids and "gnews-kw-animal-cruelty" in ids  # its plain search takes over


def test_top_level_keywords_alone_are_read():
    """The policy's top-level `keywords` (plan §6) is used when `config.keywords_v2` is missing."""
    raw = migrated()
    del raw["config"]["keywords_v2"]
    lists = lists_of(raw)
    assert lists["keywords_v2"] == raw["keywords"] and lists["keywords"] == raw["config"]["keywords"]
