def test_keyword_checks_read_the_roles_and_categories():
    lists = lists_of(migrated())
    got = {s.id: s for s in sources.load_sources_data(lists)[0]}
    include = keywords.role_words(keywords.from_data(lists), "include")
    assert got["the-hindu-environment"].keywords == include  # owner's decision 4: the Include role
    assert all(w.isascii() for w in include) and "animal rescue" in include
    assert "vivisection" in got["pfa-substack"].keywords and "vivisection" in got["peta-india"].keywords
    assert got["opp-wwf-india"].keywords  # WWF keeps its own list (decision 11)


def test_policy_lists_come_from_the_roles():
    raw = migrated()
    p = policy.Policy.from_json(raw)
    table = keywords.from_data(raw)
    assert p.strong == keywords.role_words(table, "include") and len(p.exclude) >= 28
    assert "cattle smugglers" in p.exclude and "cattle smuggler" in p.exclude  # merged record, both spellings kept
    assert p.relevance_on is bool(raw["relevance"]["enabled"])
    assert p.verdict("https://a.example/x", "gnews-kw-x", "Cattle smugglers held") == "filtered"  # Exclude always
    # phase 4: the old lists in `relevance` are never read, with or without the keyword table
    stale = {**raw, "relevance": {**raw["relevance"], "strong": ["old word"], "exclude": ["old exclude"]}}
    assert policy.Policy.from_json(stale).strong == p.strong and "old exclude" not in policy.Policy.from_json(stale).exclude
    v1 = policy.Policy.from_json({"relevance": {**raw["relevance"], "enabled": True}})
    assert v1.strong == [] and not v1.relevance_on  # no keyword table: no lists and no pre-filter (the site checks)


def test_match_word_switches_the_matcher_on_and_v1_stays_legacy():
    sources.load_sources_data(lists_of(today()))
    assert not matcher.word_mode()
    sources.load_sources_data(lists_of(migrated()))
    assert matcher.word_mode()
    src = sources.Source(id="x", name="X", kind="rss", type="news", url="u")
    # "sterilis*" (a trailing * added by the migration) still finds "sterilisation"; plain words are whole words
    assert "animal-birth-control" in sources.categories_for(sources.Item(src, "Sterilisation drive for dogs", "u", None))
    assert sources.matches_keywords(sources.Item(src, "Stray dogs fed", "u", None), ["stray dog"])
    assert not sources.matches_keywords(sources.Item(src, "Cowardly act", "u", None), ["cow"])


