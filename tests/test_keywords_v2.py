def test_run_passes_the_relevance_category_and_the_keyword_categories(monkeypatch):
    sources.load_sources_data(lists_of(migrated()))
    src = sources.Source(id="gnews-kw-stray-dog", name="Google News – stray dog", kind="rss", type="news",
                         url="https://news.google.com/rss/search?q=x", categories=["community-dogs"])
    item = sources.Item(src, "Stray dog bites child in Pune", "https://e.example/a", date(2026, 10, 25), "dogs and a vet")

    class Verdict:
        category = "Veterinary Care"
        same_as = ""

        def to_json(self):
            return {}

    class Gate:
        recent_ids: dict = {}

        def admit(self, c):
            return "pass", Verdict()

        def category_slug(self, value):
            return {"veterinary care": "veterinary-care"}.get(value.lower(), "")

    posted = []

    class Client:
        last = {}

        def post(self, payload):
            posted.append(payload)
            return "created"

    monkeypatch.setattr(sources, "collect", lambda used, body, today, lookback, limit: [item])
    monkeypatch.setattr(run.headline_case, "case_title", lambda s, t: (t, ""))
    monkeypatch.setattr(run.titles_mod, "is_cut", lambda t: False)
    monkeypatch.setattr(sources, "press_release_headline", lambda u, t: "")
    run.run([src], {}, dry_run=False, summariser=summarise.DryRunSummariser(), client=Client(), fetch=lambda u: "",
            today=date(2026, 10, 25), gate=Gate())
    assert posted and posted[0]["categories"][0] == "community-dogs" and "veterinary-care" in posted[0]["categories"]


